# -*- coding: utf-8 -*-
"""
GRAVITY の顔（アプリの中だけで使える絵文字）。2026-10-22 本人「入力欄のすぐ左の顔をタップするとグラビティアプリ内で使える
顔文字が表示されて顔をタップすると絵文字を送信できるよ」→ AI がチャットで気持ちを出すときに使う（本人「使う」）。

⚠️ 顔は文字の符号（例:「[無表情]」）として入力欄・チャット欄に入り、GRAVITY が顔の絵にして表示する。
   だから文に符号を入れて送れば顔になる。下の符号は、実機の顔の一覧で1つずつ押して入力欄に入った文字を読んだもの（2026-10-22。71個）。
   一覧に無い符号は顔にならず、ただの文字「[〜]」で出るので、送る前に外す（clean_faces）
"""
import re

FACES = ("[にこやか]", "[笑う]", "[目がハート]", "[ほほえむ]", "[照れる]", "[投げキス]", "[大笑い]",
         "[目が開いている]", "[びっくり]", "[泣き笑い]", "[大泣き]", "[目が回る]", "[ほっとする]", "[ウインク]",
         "[冷や汗]", "[無表情]", "[怒る]", "[眠い]", "[疑っている]", "[怪しむ]", "[穏やか]")
FEELINGS = ("[グラちゃん]", "[キラッ]", "[好き]", "[照れ]", "[気まずい]", "[焦る]", "[悲しい]", "[ひゅん]", "[疑問]",
            "[驚く]", "[がっかり]", "[ショック]", "[ため息]", "[溶ける]", "[ムカつく]", "[激おこ]")
WORDS = ("[ありがと]", "[おつかれ]", "[よろしく]", "[かわいい]", "[すごい]", "[がんばれ]", "[ごめん]", "[最高]", "[やば]",
         "[すき]", "[了解]", "[しんどい]", "[おかえり]", "[え]", "[草]", "[笑]", "[推]", "[尊]", "[神]", "[乾杯]",
         "[おめでとう]", "[オッケー]", "[おねがい]", "[いいね]", "[ハートポーズ]", "[パチパチ]")
THINGS = ("[惑星]", "[星]", "[ハート]", "[月]", "[UFO1]", "[UFO2]", "[ロケット]", "[星2]")
ALL_CODES = frozenset(FACES + FEELINGS + WORDS + THINGS)
# 文に符号を書いて送ると顔の絵になるもの（2026-10-23 本人「絵文字反映されてない」。実物: [ほっとする]（顔）は絵になり、
# [しんどい]（ことば）は「[しんどい]」の文字のまま出た）。⚠️ 顔の一覧の最初の21個（顔）だけにする。ことば・気持ち・もの は、
# 顔の一覧から押して入れたときだけ別の扱いになるらしく、文に書いても絵にならない（どれが絵になるか分かれば、ここに足す）
USABLE_CODES = frozenset(FACES)
MAX_FACES = 2

# 一覧に無い「[〜]」で、顔の符号らしいもの（短い・空白が無い）。⚠️ 長いもの・空白を含むものは、人が書いた文の括弧かもしれないので残す
_BRACKET = re.compile(r"\[[^\[\]\s]{1,8}\]")
# ふつうの絵文字（😊 など）。GRAVITY の顔の代わりには使わない（本人「使う」＝今の絵文字の代わりに）
_PICTOGRAPH = re.compile("[\U0001F000-\U0001FAFF\U00002600-\U000027BF\U00002B00-\U00002BFF️‍]")


def face_lines():
    """チャットで書くときに AI に渡す「## 絵文字」の中身（GRAVITY の顔の一覧と使い方）"""
    return ["## 絵文字（GRAVITY の顔）",
            "気持ちに合う GRAVITY の顔を、文の終わりなどに1〜2個まで使ってよい（使いすぎない。真面目な話・相手がつらい話では控えめに）。",
            "下の一覧の符号を、角かっこも含めてそのまま書く（一覧に無いものは顔にならない）。"
            "ふつうの絵文字（😊 など）や顔文字（(＾▽＾) など）は使わない。",
            "顔: " + " ".join(FACES),
            "（この一覧に無いもの・言葉の入ったスタンプは顔にならないので書かない）"]


def clean_faces(text):
    """
    送る前に整える: 絵にならない符号（使ってよい顔 USABLE_CODES に無い「[〜]」）とふつうの絵文字を外し、顔は MAX_FACES 個まで。
    文の中身は変えない
    """
    kept = 0

    def keep(match):
        nonlocal kept
        code = match.group(0)
        if code not in USABLE_CODES:
            return ""
        kept += 1
        return code if kept <= MAX_FACES else ""
    text = _BRACKET.sub(keep, text or "")
    text = _PICTOGRAPH.sub("", text)
    return re.sub(r"[ \t　]{2,}", " ", text).strip()
